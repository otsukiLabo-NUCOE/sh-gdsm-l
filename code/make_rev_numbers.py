def exp4():
    def per_seed(pattern):
        rows = {}
        for f in glob.glob(pattern):
            for arm, rs in load(f)["per_seed"].items():
                rows.setdefault(arm, {}).update({r["seed"]: r for r in rs})
        return rows
    son, opu = per_seed("EL/exp4_sonnet_s*.json"), per_seed("EL/exp4_opus_s*.json")
    old = {**load("llm_results_real_ABD.json")["results"], **load("llm_results_real_D.json")["results"]}
    cr = load("results_rev_exp4_CR.json")
    eps = 30

    def cell(d, arm):
        v = [r["completion"] for r in d[arm].values()]
        m, h = ci95(v)
        return m, h, S.fmean(r["llm_calls"] / eps for r in d[arm].values()), \
            sum(r.get("cost_usd", 0) for r in d[arm].values()) / (eps * len(v)), len(v)
    rows = []
    names = {"A": "A\\ \\ LLM decides (delegated)", "B": "B\\ \\ LLM + reflect-and-retry",
             "D": "D\\ \\ LLM + learned $\\rel$ hint"}
    for arm in "ABD":
        sm, sh, sc, scost, ns = cell(son, arm)
        om, oh, oc, ocost, no = cell(opu, arm)
        rows.append([names[arm], pc(old[arm]["completion"]), f"{pc(sm)} $\\pm$ {pc(sh)}",
                     f"{pc(om)} $\\pm$ {pc(oh)}", f"{sc:.1f}", f"{oc:.1f}", f"{scost:.3f}"])
        macro(f"NRevFour{arm}Son", pc(sm)); macro(f"NRevFour{arm}Opus", pc(om))
        macro(f"NRevFour{arm}SonCalls", f"{sc:.1f}"); macro(f"NRevFour{arm}Old", pc(old[arm]["completion"]))
        macro(f"NRevFour{arm}SonCost", f"{scost:.3f}")
    macro("NRevFourSonSeeds", str(ns)); macro("NRevFourOpusSeeds", str(no)); macro("NRevFourEps", str(eps))
    # what the transition rule removes: B (reflect-and-retry) against C+R
    bo = cell(opu, "B")
    macro("NRevFourBOpusCalls", f"{bo[2]:.1f}"); macro("NRevFourBOpusCost", f"{bo[3]:.3f}")
    for pat, k in (("EL/exp4_sonnet_s*.json", "Son"), ("EL/exp4_opus_s*.json", "Opus")):
        res = [load(f)["results"]["B"] for f in glob.glob(pat)]
        macro(f"NRevFourB{k}Sec", f"{S.fmean(r['seconds_per_episode'] for r in res):.1f}")
        macro(f"NRevFourB{k}CallLat", f"{S.fmean(r['mean_call_latency_s'] for r in res):.1f}")
    bs = cell(son, "B")
    macro("NRevFourBSonMillionCalls", f"{bs[2]:.1f}")
    macro("NRevFourBSonMillionUSD", f"{1e6 * bs[3]:,.0f}".replace(",", "{,}"))
    if os.path.exists("results_rev_exp4_CR_time.json"):
        t = load("results_rev_exp4_CR_time.json")
        macro("NRevFourCRDecMs", f"{t['decision_ms']:.2f}"); macro("NRevFourCREpMs", f"{t['episode_ms']:.1f}")
        macro("NRevFourCRRepro", pc(t["reproduced"], 0)); macro("NRevFourCRReproN", f"{t['episodes']:,}".replace(",", "{,}"))
    rows.append("MID")
    for arm, lab in (("C", "C\\ \\ \\model (no retry)"), ("C+R", "C+R\\ \\model{} + retry")):
        rows.append([lab, pc(cr[arm]["completion"]), "\\multicolumn{2}{c}{no model call}",
                     "", "0", "0", "0"])
    for i, arm in ((-2, "C"), (-1, "C+R")):
        rows[i] = [rows[i][0], "\\multicolumn{3}{c}{" + f"{pc(cr[arm]['completion'])} $\\pm$ "
                   f"{pc(cr[arm]['ci'])} (no model call)" + "}", "0", "0", "0"]
    macro("NRevFourC", pc(cr["C"]["completion"])); macro("NRevFourCR", pc(cr["C+R"]["completion"]))
    macro("NRevFourCRci", pc(cr["C+R"]["ci"])); macro("NRevFourCRSteps", f"{cr['C+R']['steps']:.1f}")
    macro("NRevFourBSonSteps", f"{S.fmean(r['steps'] for r in son['B'].values()):.1f}")
    table("exp4", ["Arm", "9B (subm.)", "Sonnet 5.5", "Opus 5.5", "Calls/ep. S", "Calls/ep. O", "USD/ep. S"],
          rows, "lrrrrrr")
    tot = sum(r.get("cost_usd", 0) for d in (son, opu) for a in d.values() for r in a.values())
    return tot


def toolmaze():
    def runs(paths):
        by = {}
        for p in paths:
            if os.path.exists(p):
                for r in load(p)["runs"]:
                    if "error" not in r:
                        by.setdefault(r["task_id"], {})[r["arm"]] = r
        return by
    rows, cost = [], 0.0
    p0 = load("EL/toolmaze_P0_sonnet.json")["runs"]
    cost += sum(r.get("cost_usd", 0) for r in p0)
    n0, k0 = len(p0), sum(r["passed"] for r in p0)
    rows.append(["P0 (no perturbation)", f"{n0}", f"{pc(k0 / n0)}", "--", "--", "--", "--"])
    macro("NRevTmPzero", pc(k0 / n0)); macro("NRevTmPzeroN", str(n0))
    for m in ("P2", "P4"):
        by = runs([f"EL/toolmaze_{m}_sonnet.json", f"EL/toolmaze_{m}_sonnet_h.json"])
        for v in by.values():
            cost += sum(r.get("cost_usd", 0) for r in v.values())
        pairs = [v for v in by.values() if "llm" in v and "hybrid-h" in v]
        old = [v for v in by.values() if "llm" in v and "hybrid" in v]
        n = len(pairs)
        L = sum(v["llm"]["passed"] for v in pairs) / n
        H = sum(v["hybrid-h"]["passed"] for v in pairs) / n
        O = sum(v["hybrid"]["passed"] for v in old) / len(old)
        b = sum(1 for v in pairs if v["hybrid-h"]["passed"] and not v["llm"]["passed"])
        c = sum(1 for v in pairs if v["llm"]["passed"] and not v["hybrid-h"]["passed"])
        p = binomtest(b, b + c).pvalue if b + c else 1.0
        cl = S.fmean(v["llm"]["llm_calls"] for v in pairs)
        ch = S.fmean(v["hybrid-h"]["llm_calls"] for v in pairs)
        lab = "P2 (persistent errors)" if m == "P2" else "P4 (semantic corruption)"
        rows.append([lab, f"{n}", pc(L), f"{pc(O)} ({len(old)})", pc(H), f"{b} / {c}", pval(p)])
        macro(f"NRevTm{m}Llm", pc(L)); macro(f"NRevTm{m}Hyb", pc(H)); macro(f"NRevTm{m}Old", pc(O))
        macro(f"NRevTm{m}N", str(n)); macro(f"NRevTm{m}b", str(b)); macro(f"NRevTm{m}c", str(c))
        macro(f"NRevTm{m}p", pval(p)); macro(f"NRevTm{m}CallsLlm", f"{cl:.1f}"); macro(f"NRevTm{m}CallsHyb", f"{ch:.1f}")
        macro(f"NRevTm{m}OldN", str(len(old)))
    # held-out replication: P2 with Opus 5.5, hand-over hybrid fixed before this run
    if os.path.exists("EL/toolmaze_P2_opus_llm.json") and os.path.exists("EL/toolmaze_P2_opus_hybrid-h.json"):
        by = runs(["EL/toolmaze_P2_opus_llm.json", "EL/toolmaze_P2_opus_hybrid-h.json"])
        for v in by.values():
            cost += sum(r.get("cost_usd", 0) for r in v.values())
        pairs = [v for v in by.values() if "llm" in v and "hybrid-h" in v]
        n = len(pairs)
        L = sum(v["llm"]["passed"] for v in pairs) / n
        H = sum(v["hybrid-h"]["passed"] for v in pairs) / n
        b = sum(1 for v in pairs if v["hybrid-h"]["passed"] and not v["llm"]["passed"])
        c = sum(1 for v in pairs if v["llm"]["passed"] and not v["hybrid-h"]["passed"])
        p = binomtest(b, b + c).pvalue if b + c else 1.0
        cl = S.fmean(v["llm"]["llm_calls"] for v in pairs)
        ch = S.fmean(v["hybrid-h"]["llm_calls"] for v in pairs)
        rows.append(["P2, Opus 5.5", f"{n}", pc(L), "--", pc(H), f"{b} / {c}", pval(p)])
        macro("NRevTmOpusLlm", pc(L)); macro("NRevTmOpusHyb", pc(H)); macro("NRevTmOpusN", str(n))
        macro("NRevTmOpusb", str(b)); macro("NRevTmOpusc", str(c)); macro("NRevTmOpusp", pval(p))
        macro("NRevTmOpusCallsLlm", f"{cl:.1f}"); macro("NRevTmOpusCallsHyb", f"{ch:.1f}")
        macro("NRevTmOpusDiff", f"{100 * (H - L):.1f}")
    table("toolmaze", ["Mode", "Tasks", "LLM alone", "Hybrid (orig.)", "Hybrid + hand-over",
                       "Wins H / L", "McNemar $p$"], rows, "lrrrrrr")
    # learned pairs and interventions
    hp = load("EL/toolmaze_P2_sonnet_h.json")
    macro("NRevTmPretrain", str(hp["pretraining"]["pass_observations"]))
    iv = [i for r in hp["runs"] if r.get("interventions") for i in r["interventions"]]
    macro("NRevTmIntervShare", pc(sum(1 for i in iv if i["chosen"]) / max(1, len(iv)), 0))
    return cost


def s4_merged(names):
    """Scenario S4 with Sonnet 5.5 over all seeds: seeds 1-3 from the log of the
    first run, further seeds from EL/exp6_sonnet_S4_s*.json (per-seed cells)."""
    extra = sorted(glob.glob("EL/exp6_sonnet_S4_s*.json"))
    if not extra:
        return None
    lab = {"C": "C", "A": "A-llm", "B": "B-llm", "C+H": "C+H"}
    cells = {a: {} for a in names}
    for line in open("EL/exp6_sonnet_S4.log", encoding="utf-8"):
        t = line.split(" ", 3)
        if len(t) == 4 and t[0] == "S4" and t[1] in lab:
            cells[lab[t[1]]][int(t[2])] = json.loads(t[3].replace("NaN", "null"))
    for f in extra:
        for line in open(f.replace(".json", ".log"), encoding="utf-8"):
            t = line.split(" ", 3)
            if len(t) == 4 and t[0] == "S4" and t[1] in lab:
                cells[lab[t[1]]][int(t[2])] = json.loads(t[3].replace("NaN", "null"))
    seeds = sorted(set.intersection(*(set(v) for v in cells.values())))
    arms = {}
    for a in names:
        cs = [cells[a][s] for s in seeds]
        m, h = ci95([c["completion"] for c in cs])
        arms[a] = dict(completion=m, completion_ci=h,
                       calls_per_episode=S.fmean(c["calls_per_episode"] for c in cs),
                       cost_total=sum(c.get("cost_usd", 0) or 0 for c in cs))
    from scipy.stats import wilcoxon
    def wp(x, y):
        xs = [cells[x][s]["completion"] for s in seeds]; ys = [cells[y][s]["completion"] for s in seeds]
        return 1.0 if all(a == b for a, b in zip(xs, ys)) else wilcoxon(xs, ys).pvalue
    macro("NRevSixSFourSeeds", str(len(seeds)))
    macro("NRevSixSFourEps", str(12 * len(seeds)))
    macro("NRevSixSFourCHci", pc(arms["C+H"]["completion_ci"]))
    macro("NRevSixSFourAci", pc(arms["A-llm"]["completion_ci"]))
    macro("NRevSixSFourpA", pval(wp("C+H", "A-llm")))
    macro("NRevSixSFourpB", pval(wp("C+H", "B-llm")))
    macro("NRevSixSFourpC", pval(wp("C+H", "C")))
    return dict(arms=arms, seeds=seeds)


def exp6():
    rows, cost = [], 0.0
    names = {"C": "C\\ \\ \\model", "A-llm": "A\\ \\ LLM decides", "B-llm": "B\\ \\ LLM + retry",
             "C+H": "C+H\\ \\model{} + hand-over"}
    calls = {k: [] for k in names}
    proxy = load("results_recovery_v4.json")["main"]
    gaps = []
    s4 = s4_merged(names)
    for f in sorted(glob.glob("EL/exp6_sonnet_S*.json")):
        if "_s" in os.path.basename(f)[len("exp6_sonnet_S4"):]:
            continue                      # extra S4 seeds are merged by s4_merged()
        d = load(f)
        if s4 and "S4" in d["results"]:
            d = dict(d, results={"S4": s4["arms"]})
        for scn, arms in d["results"].items():
            gaps.append(abs(proxy[scn]["A"]["completion"] - arms["A-llm"]["completion"]))
        for scn, arms in d["results"].items():
            for arm in names:
                v = arms[arm]
                cost += v["cost_total"] if "cost_total" in v else (v.get("cost_usd", 0) or 0) * d["seeds"]
                calls[arm].append(v["calls_per_episode"])
            rows.append([scn] + [pc(arms[a]["completion"]) for a in names] +
                        [f"{arms[a]['calls_per_episode']:.1f}" for a in ("A-llm", "B-llm", "C+H")])
            macro(f"NRevSix{scn}C", pc(arms["C"]["completion"])); macro(f"NRevSix{scn}CH", pc(arms["C+H"]["completion"]))
            macro(f"NRevSix{scn}A", pc(arms["A-llm"]["completion"])); macro(f"NRevSix{scn}B", pc(arms["B-llm"]["completion"]))
        macro("NRevSixSeeds", str(d["seeds"])); macro("NRevSixEps", str(d["episodes"]))
    for arm in ("A-llm", "B-llm", "C+H"):
        k = arm.replace("-llm", "").replace("+", "")
        macro(f"NRevSix{k}CallsMin", f"{min(calls[arm]):.1f}"); macro(f"NRevSix{k}CallsMax", f"{max(calls[arm]):.1f}")
    macro("NRevSixProxyGap", f"{100 * S.fmean(gaps):.1f}")
    macro("NRevSixProxyGapMax", f"{100 * max(gaps):.1f}")
    table("exp6llm", ["Sc.", "C", "A", "B", "C+H", "Calls A", "Calls B", "Calls C+H"], rows, "lrrrrrrr")
    return cost


