    spec = [("Validator accuracy 1.0 (nominal)", "EN", "acc=1.0 (nominal)"),
            ("accuracy 0.9", "EN", "acc=0.9"), ("\\quad + noise model", "ENC", "acc=0.9 +noise model"),
            ("accuracy 0.7", "EN", "acc=0.7"), ("\\quad + noise model", "ENC", "acc=0.7 +noise model"),
            ("\\quad + noise model, accuracy assumed 0.8", "ENC", "acc=0.7 +noise model (assumed 0.8)"),
            ("\\quad + noise model, accuracy assumed 0.6", "ENC", "acc=0.7 +noise model (assumed 0.6)"),
            ("accuracy 0.5 (uninformative)", "EN", "acc=0.5"),
            ("80\\% of verdicts missing", "EN", "missing=0.8"),
            ("\\quad + soft attribution", "ENC", "missing=0.8 +soft attribution"),
            ("outcome only (no verdicts)", "EN", "outcome-only"),
            ("\\quad + soft attribution", "ENC", "outcome-only +soft attribution")]
    for lab, part, setting in spec:
        summ = en if part == "EN" else enc
        r = get(summ, f"{part} | reference", setting)
        q = get(summ, f"{part} | K=8", setting)
        rows.append([lab, pc(r["real"]), pt(r["gap"]), f3(r["ece"]), pc(q["real"]), pt(q["gap"]), f3(q["ece"])])
    table("noise", ["Supervision", "Real.", "Gap", "ECE", "Real.", "Gap", "ECE"], rows, "lrrrrrr")
    r = lambda part, s, k="reference": get(en if part == "EN" else enc, f"{part} | {k}", s)
    macro("NRevNoiseSevenGap", pt(r("EN", "acc=0.7")["gap"])); macro("NRevNoiseSevenEce", f3(r("EN", "acc=0.7")["ece"]))
    macro("NRevNoiseSevenCorrEce", f3(r("ENC", "acc=0.7 +noise model")["ece"]))
    macro("NRevNoiseOutEce", f3(r("EN", "outcome-only")["ece"])); macro("NRevNoiseOutGap", pt(r("EN", "outcome-only")["gap"]))
    macro("NRevNoiseOutCorrEce", f3(r("ENC", "outcome-only +soft attribution")["ece"]))
    macro("NRevNoiseHalfReal", pc(r("EN", "acc=0.5")["real"]))
    worst_real_drop = max(get(en, f"EN | {u}", "acc=1.0 (nominal)")["real"] - get(en, f"EN | {u}", s)["real"]
                          for u in ("reference", "K=8")
                          for s in ("missing=0.2", "missing=0.5", "missing=0.8", "outcome-only", "acc=0.9", "acc=0.7"))
    macro("NRevNoiseMaxDrop", f"{100 * worst_real_drop:.1f}")
    # completion cost of the corrections (correct assumed accuracy / soft attribution) against nominal
    corr_drop = max(get(en, f"EN | {u}", "acc=1.0 (nominal)")["real"] - get(enc, f"ENC | {u}", s)["real"]
                    for u in ("reference", "K=8")
                    for s in ("acc=0.9 +noise model", "acc=0.7 +noise model", "missing=0.8 +soft attribution",
                              "outcome-only +soft attribution"))
    macro("NRevNoiseCorrMaxDrop", f"{100 * corr_drop:.1f}")
    macro("NRevNoiseHiAssumeEce", f3(r("ENC", "acc=0.7 +noise model (assumed 0.8)")["ece"]))
    macro("NRevNoiseLoAssumeEce", f3(r("ENC", "acc=0.7 +noise model (assumed 0.6)")["ece"]))
    macro("NRevNoiseLoAssumeDrop", f"{-100 * r('ENC', 'acc=0.7 +noise model (assumed 0.6)')['diff_real']:.1f}")

    # ablation
    rows = []
    for setting, lab in (("full", "\\model{} (full)"), ("-schema learning", "$-$schema-pair learning"),
                         ("-reliability learning", "$-$reliability learning"),
                         ("-LCB (mean, theta=0.12)", "$-$LCB (posterior mean, $\\theta=0.12$)"),
                         ("-LCB (mean, theta=0)", "$-$LCB (posterior mean, $\\theta=0$)"),
                         ("-look-ahead (greedy)", "$-$look-ahead (greedy)"),
                         ("-dynamic (fixed plan)", "$-$dynamic re-selection (fixed plan)")):
        a = get(en, "EA | reference", setting)
        b = get(en, "EA | K=8", setting)
        d = lambda x: (f"{100 * x['diff_real']:+.1f} ({pval(x['wilcoxon_p'])})" if "diff_real" in x else "--")
        rows.append([lab, pc(a["real"]), pt(a["gap"]), f3(a["ece"]), d(a), pc(b["real"]), pt(b["gap"]), d(b)])
    table("ablation", ["Variant", "Real.", "Gap", "ECE", "$\\Delta$ ($p$)", "Real.", "Gap", "$\\Delta$ ($p$)"],
          rows, "lrrrrrrr")
    for key, s in (("Schema", "-schema learning"), ("Dyn", "-dynamic (fixed plan)"), ("NoTheta", "-LCB (mean, theta=0)")):
        macro(f"NRevAbl{key}Ref", f"{100 * get(en, 'EA | reference', s)['diff_real']:+.1f}")
        macro(f"NRevAbl{key}Rand", f"{100 * get(en, 'EA | K=8', s)['diff_real']:+.1f}")
        macro(f"NRevAbl{key}RefGap", pt(get(en, 'EA | reference', s)['gap']))
        macro(f"NRevAbl{key}RandGap", pt(get(en, 'EA | K=8', s)['gap']))

    # baselines
    eb = load("results_rev_EB.json")["summary"]
    rows = []
    for arm, lab in (("SH-GD/SM-L", "\\model"), ("tool-bandit", "Tool-level Bayesian bandit \\cite{xu2026ael,forouzandeh2025hierarchical}"),
                     ("similarity", "Name/description similarity"), ("exact-match", "Exact match only"),
                     ("oracle", "(ref.) Oracle $\\rel$, $\\phat$, same policy"), ("optimal", "(ref.) Optimal policy (exact DP)")):
        cells = []
        for uni in ("reference", "reference (transfer)", "K=8", "K=8 (transfer)"):
            v = eb.get(f"{uni} | {arm}")
            if v is None:
                cells.append("--")
                continue
            s = pc(v["real"])
            if v.get("wilcoxon_p") is not None and arm not in ("oracle", "optimal"):
                s += "$^{*}$" if v["wilcoxon_p"] < 0.01 else ""
            cells.append(s)
        rows.append([lab] + cells)
    table("baselines", ["Model", "Reference", "Ref., transfer", "Random $K{=}8$", "$K{=}8$, transfer"], rows, "lrrrr")
    for arm, k in (("tool-bandit", "Bandit"), ("similarity", "Sim"), ("exact-match", "Exact")):
        macro(f"NRevBase{k}Ref", pc(eb[f"reference | {arm}"]["real"]))
        macro(f"NRevBase{k}Rand", pc(eb[f"K=8 | {arm}"]["real"]))
        macro(f"NRevBase{k}RefTr", pc(eb[f"reference (transfer) | {arm}"]["real"]))
        macro(f"NRevBase{k}RandTr", pc(eb[f"K=8 (transfer) | {arm}"]["real"]))
    macro("NRevBaseOursRand", pc(eb["K=8 | SH-GD/SM-L"]["real"])); macro("NRevBaseOracleRand", pc(eb["K=8 | oracle"]["real"]))
    macro("NRevBaseOursRandTr", pc(eb["K=8 (transfer) | SH-GD/SM-L"]["real"]))

    # context and correlated failures
    ek = load("results_rev_EK.json")["summary"]
    for kind, k in (("ctx-strong", "Strong"), ("ctx-strong-weak-alt", "Weak"), ("ctx-none", "None")):
        for mode in ("free", "ctx", "backoff"):
            v = ek[f"{kind} | {mode}"]
