OUT = "."
MAC: Dict[str, str] = {}


def load(p):
    return json.load(open(p, encoding="utf-8"))


DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]


def macro(name, value):
    """LaTeX macro names cannot contain digits: 1 -> One, ..."""
    name = "".join(DIGITS[int(ch)] if ch.isdigit() else ch for ch in name)
    MAC[name] = value


def pc(x, d=1):
    return f"{100 * x:.{d}f}"


def pt(x, d=1):
    return f"{100 * x:+.{d}f}"


def f3(x):
    return f"{x:.3f}"


def pval(p):
    if p is None:
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def table(name, header, rows, align):
    lines = ["% generated by make_rev_numbers.py -- do not edit",
             f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        if r == "MID":
            lines.append("\\midrule")
        else:
            lines.append(" & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(OUT, "tables", f"rev_{name}.tex"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def ci95(xs):
    m = S.fmean(xs)
    return m, (1.96 * S.stdev(xs) / len(xs) ** 0.5 if len(xs) > 1 else 0.0)


