def drift():
    s1 = load("results_rev_ED.json")
    s2 = load("results_rev_ED_alarm.json")
    summ = {**s1["summary"], **s2["summary"]}
    rows_all = s1["rows"] + s2["rows"]
    names = {"drift": "FetchStockA $p$ 0.80$\\rightarrow$0.30", "drift-news": "FetchNews $p$ 0.90$\\rightarrow$0.20",
             "withdraw": "FetchEcon withdrawn", "add": "FetchEconB added",
             "overlap": "$\\rho^*$(market$\\rightarrow$stock) 0.85$\\rightarrow$0.20"}
    rows = []
    for sc, lab in names.items():
        cells = []
        for g in ("1.0", "0.995", "0.98", "alarm"):
            v = summ[f"{sc} | gamma={g}"]
            cells.append(f"{100 * v['post_abs_gap']:.1f} / {pt(v['final_gap'])}")
        # over-claim alarm (gamma = 1): detection share and median delay
        rs = [r for r in rows_all if r["scenario"] == sc and r["gamma"] == 1.0]
        hits = []
        for sd in sorted({r["seed"] for r in rs}):
            post = sorted((r for r in rs if r["seed"] == sd and r["episode"] > 800), key=lambda r: r["episode"])
            h = next((r["episode"] - 800 for r in post if r["alarm_over"]), None)
            if h is not None:
                hits.append(h)
        det = f"{len(hits)}/10" + (f" ({int(S.median(hits))})" if hits else "")
        rows.append([lab] + cells + [det])
    fa = S.fmean(float(r["alarm_over"]) for r in rows_all if r["gamma"] == 1.0 and r["episode"] <= 800)
    macro("NRevDriftFA", f"{fa:.3f}")
    table("drift", ["Change at episode 800", "$\\gamma=1$", "$\\gamma=0.995$", "$\\gamma=0.98$",
                    "alarm-triggered", "Over-claim alarm"], rows, "lrrrrr")
    for g, k in (("1.0", "One"), ("0.995", "Slow"), ("0.98", "Fast"), ("alarm", "Alarm")):
        macro(f"NRevDriftNews{k}", f"{100 * summ[f'drift-news | gamma={g}']['post_abs_gap']:.1f}")
        macro(f"NRevDriftWd{k}Final", pt(summ[f"withdraw | gamma={g}"]["final_gap"]))


